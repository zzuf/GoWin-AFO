func TestStagedRawDumpIsNotWrittenOnSliceFailure(t *testing.T) {
	root := tempGenerationRoot(t)
	result, err := Generate(context.Background(), GenerateOptions{Root: root, Write: true})
	if err != nil {
		t.Fatal(err)
	}
	raw, err := emit.Render(result.Inventory, "example.com/renamed")
	if err != nil {
		t.Fatal(err)
	}
	reviewed, err := slice.Render(root, "example.com/renamed", Version)
	if err != nil {
		t.Fatal(err)
	}
	dump := filepath.Join(root, "coverage", "raw", "fixture.json")
	if err := os.MkdirAll(filepath.Dir(dump), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(dump, []byte("{\"prior\":true}\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := writeGeneration(root, result.Inventory, result.Coverage, raw, reviewed, map[string][]byte{"coverage/raw/fixture.json": []byte("{\"next\":true}\n")}); err != nil {
		t.Fatal(err)
	}
	if got, err := os.ReadFile(dump); err != nil || string(got) != "{\"next\":true}\n" {
		t.Fatalf("raw dump was not committed with generation: %q, %v", got, err)
	}
	blocked := filepath.Join(root, "bindings", "win32", "foundation", "ztypes_base.go")
	if err := os.Remove(blocked); err != nil {
		t.Fatal(err)
	}
	if err := os.Mkdir(blocked, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := writeGeneration(root, result.Inventory, result.Coverage, raw, reviewed, map[string][]byte{"coverage/raw/fixture.json": []byte("{\"after\":true}\n")}); err == nil {
		t.Fatal("expected blocked slice destination")
	}
	if got, err := os.ReadFile(dump); err != nil || string(got) != "{\"next\":true}\n" {
		t.Fatalf("raw dump changed after failure: %q, %v", got, err)
	}
}

func TestGenerationRollbackRetainsBackupWhenRestoreFails(t *testing.T) {
	for _, failRestore := range []bool{false, true} {
		name := "restores"
		if failRestore {
			name = "retains-backup"
		}
		t.Run(name, func(t *testing.T) {
			root := t.TempDir()
			stage := filepath.Join(root, "stage")
			for _, name := range []string{"a", "b"} {
				for _, base := range []string{root, stage} {
					path := filepath.Join(base, "coverage", name)
					if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
						t.Fatal(err)
					}
					if err := os.WriteFile(path, []byte(base), 0o644); err != nil {
						t.Fatal(err)
					}
				}
			}
			installFailure := errors.New("injected install failure")
			restoreFailure := errors.New("injected restore failure")
			ops := transactionOps{rename: func(from, to string) error {
				if from == filepath.Join(stage, "coverage", "b") && to == filepath.Join(root, "coverage", "b") {
					return installFailure
				}
				if failRestore && from == filepath.Join(stage, "backups", "0000") {
					return restoreFailure
				}
				return os.Rename(from, to)
			}, remove: os.Remove, removeAll: os.RemoveAll}
			err := commitGenerationWithOps(root, stage, []generatedTarget{{path: "coverage/a"}, {path: "coverage/b"}}, ops)
			if !errors.Is(err, installFailure) {
				t.Fatalf("missing install error: %v", err)
			}
			if got, err := os.ReadFile(filepath.Join(root, "coverage", "b")); err != nil || string(got) != root {
				t.Fatalf("second target was not restored: %q, %v", got, err)
			}
			if failRestore {
				var retained *retainedStageError
				if !errors.Is(err, restoreFailure) || !errors.As(err, &retained) || !strings.Contains(err.Error(), stage) {
					t.Fatalf("restore failure and backup path not reported: %v", err)
				}
				if got, err := os.ReadFile(filepath.Join(stage, "backups", "0000")); err != nil || string(got) != root {
					t.Fatalf("backup not retained: %q, %v", got, err)
				}
			} else if got, err := os.ReadFile(filepath.Join(root, "coverage", "a")); err != nil || string(got) != root {
				t.Fatalf("first target was not restored: %q, %v", got, err)
			}
		})
	}
}

func tempGenerationRoot(t *testing.T) string {
	t.Helper()
	project, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	root := t.TempDir()
	for _, path := range []string{"sources.lock.json", "generator/testdata/e2e/source.json"} {
		data, err := os.ReadFile(filepath.Join(project, filepath.FromSlash(path)))
		if err != nil {
			t.Fatal(err)
		}
		dest := filepath.Join(root, filepath.FromSlash(path))
		if err := os.MkdirAll(filepath.Dir(dest), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(dest, data, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	if err := os.WriteFile(filepath.Join(root, "go.mod"), []byte("module example.com/renamed\n\ngo 1.24.0\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	return root
}
