func TestGenerateRecreatesReviewedSliceWithRootModule(t *testing.T) {
	root := tempGenerationRoot(t)
	for i := 0; i < 2; i++ {
		if _, err := Generate(context.Background(), GenerateOptions{Root: root, Write: true}); err != nil {
			t.Fatal(err)
		}
	}
	path := filepath.Join(root, "bindings", "win32", "kernel32", "zfunctions_kernel_windows.go")
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Contains(data, []byte(`"example.com/renamed/runtime/winabi"`)) {
		t.Fatal("root module path was not propagated to reviewed slice")
	}
	if err := os.Remove(path); err != nil {
		t.Fatal(err)
	}
	if _, err := Generate(context.Background(), GenerateOptions{Root: root, Write: true}); err != nil {
		t.Fatal(err)
	}
	restored, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(restored, data) {
		t.Fatal("deleted slice output was not reconstructed deterministically")
	}
}

func TestGenerateSliceFailurePreservesRawTreeAndReports(t *testing.T) {
	root := tempGenerationRoot(t)
	if _, err := Generate(context.Background(), GenerateOptions{Root: root, Write: true}); err != nil {
		t.Fatal(err)
	}
	raw := filepath.Join(root, "bindings", "generated", "windows_win32_foundation", "ztypes_generated.go")
	report := filepath.Join(root, "coverage", "latest.json")
	previousRaw := []byte("// Code generated by winapigen 0.1.0; DO NOT EDIT.\n// previous raw tree\npackage foundation\n")
	if err := os.WriteFile(raw, previousRaw, 0o644); err != nil {
		t.Fatal(err)
	}
	previousReport, err := os.ReadFile(report)
	if err != nil {
		t.Fatal(err)
	}
	blocked := filepath.Join(root, "bindings", "win32", "foundation", "ztypes_base.go")
	if err := os.Remove(blocked); err != nil {
		t.Fatal(err)
	}
	if err := os.Mkdir(blocked, 0o755); err != nil {
		t.Fatal(err)
	}
	if _, err := Generate(context.Background(), GenerateOptions{Root: root, Write: true}); err == nil {
		t.Fatal("expected blocked slice destination")
	}
	if got, err := os.ReadFile(raw); err != nil || !bytes.Equal(got, previousRaw) {
		t.Fatalf("raw tree changed after failed generation: %q, %v", got, err)
	}
	if got, err := os.ReadFile(report); err != nil || !bytes.Equal(got, previousReport) {
		t.Fatalf("report changed after failed generation: %q, %v", got, err)
	}
}

